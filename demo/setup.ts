import { chmod, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import type { Pool } from "pg";

import { loadConfig } from "../src/config.js";
import { createPool } from "../src/db/pool.js";
import { provisionAccount } from "../src/modules/accounts/provision-account.js";
import {
  DemoApiClient,
  normalizeServiceUrl,
  type DemoClientConfig
} from "./client.js";

export interface CreateDemoFixtureOptions {
  serviceUrl: string;
  apiKeyPepper: string;
  accountName?: string;
}

export interface CreatedDemoFixture {
  accountId: string;
  config: DemoClientConfig;
}

export async function createDemoFixture(
  pool: Pool,
  options: CreateDemoFixtureOptions
): Promise<CreatedDemoFixture> {
  const serviceUrl = normalizeServiceUrl(options.serviceUrl);
  const account = await provisionAccount(pool, {
    name: options.accountName ?? `Quota Demo ${new Date().toISOString()}`,
    apiKeyPepper: options.apiKeyPepper
  });
  const api = new DemoApiClient({ serviceUrl, apiKey: account.apiKey });

  const accountPlan = await api.createPlan({
    name: "Demo Account",
    scope: "account",
    monthlyLimit: 30,
    requestLimit: 100
  });
  const basicPlan = await api.createPlan({
    name: "Demo Basic",
    scope: "user",
    monthlyLimit: 10,
    requestLimit: 5
  });
  const premiumPlan = await api.createPlan({
    name: "Demo Premium",
    scope: "user",
    monthlyLimit: 30,
    requestLimit: 20
  });

  await api.assignAccountPlan(accountPlan.id);
  const basicUser = await api.createUser(basicPlan.id);
  const premiumUser = await api.createUser(premiumPlan.id);

  return {
    accountId: account.id,
    config: {
      serviceUrl,
      apiKey: account.apiKey,
      accountPlanId: accountPlan.id,
      basicUserId: basicUser.id,
      premiumUserId: premiumUser.id
    }
  };
}

export async function writeDemoEnvironment(
  outputPath: string,
  config: DemoClientConfig
): Promise<void> {
  const contents = [
    "# Generated by npm run demo:setup. Contains a live API key; do not commit.",
    `DEMO_SERVICE_URL=${config.serviceUrl}`,
    `DEMO_API_KEY=${config.apiKey}`,
    `DEMO_ACCOUNT_PLAN_ID=${config.accountPlanId}`,
    `DEMO_BASIC_USER_ID=${config.basicUserId}`,
    `DEMO_PREMIUM_USER_ID=${config.premiumUserId}`,
    ""
  ].join("\n");

  await writeFile(outputPath, contents, { encoding: "utf8", mode: 0o600 });
  await chmod(outputPath, 0o600);
}

async function main(): Promise<void> {
  const appConfig = loadConfig();
  const pool = createPool(appConfig.DATABASE_URL);
  const serviceUrl = normalizeServiceUrl(
    process.env.DEMO_SERVICE_URL ?? "http://127.0.0.1:3000"
  );
  const outputPath = fileURLToPath(new URL(".demo.env", import.meta.url));

  try {
    const fixture = await createDemoFixture(pool, {
      serviceUrl,
      apiKeyPepper: appConfig.API_KEY_PEPPER
    });
    await writeDemoEnvironment(outputPath, fixture.config);

    console.log(`Created fresh dedicated demo account ${fixture.accountId}.`);
    console.log("Created Demo Account, Demo Basic, and Demo Premium through the API.");
    console.log("Registered one Basic user and one Premium user.");
    console.log(`Saved private client configuration to ${outputPath}.`);
    console.log("The raw API key was not printed. Run npm run demo:run next.");
  } finally {
    await pool.end();
  }
}

const invokedFile = process.argv[1];
if (
  invokedFile !== undefined &&
  import.meta.url === pathToFileURL(resolve(invokedFile)).href
) {
  try {
    await main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : "Demo setup failed.");
    process.exitCode = 1;
  }
}
